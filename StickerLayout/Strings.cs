    {
        Code = code;
        foreach (var (k, v) in S) Application.Current.Resources[k] = code == "en" ? v.En : v.Id;
    }

    public static string T(string key, params object[] args)
    {
        var f = Code == "en" ? S[key].En : S[key].Id;
        return args.Length == 0 ? f : string.Format(f, args);
